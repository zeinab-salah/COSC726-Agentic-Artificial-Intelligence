        "    \"\"\"Greedy longest-match tokenisation against a vocab; unknown chars stand alone.\"\"\"\n",
        "    vocab = sorted(vocab, key=len, reverse=True)\n",
        "    text, out, i = text.lower(), [], 0\n",
        "    while i < len(text):\n",
        "        for v in vocab:\n",
        "            if v and text.startswith(v.lower(), i):\n",
        "                out.append(v)\n",
        "                i += len(v)\n",
        "                break\n",
        "        else:\n",
        "            out.append(text[i])\n",
        "            i += 1\n",
        "    return out\n",
